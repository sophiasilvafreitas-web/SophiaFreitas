# Solicita ao usuário que digite o valor da base do triângulo
base = float(input("Digite a base do triângulo: "))

# Solicita ao usuário que digite o valor da altura do triângulo
altura = float(input("Digite a altura do triângulo: "))

# Calcula a área do triângulo usando a fórmula: (base * altura) / 2
area = (base * altura) / 2

# Exibe o resultado da área calculada
print("A área do triângulo é:", area)
